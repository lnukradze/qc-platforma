/**
 * ტექსტის ნორმალიზება — იგივე, რაც taxonomy.N().
 *
 * ⚠️ Python-ის `\bslr\b|\bსლრ\b|\bესელერ` პირდაპირ ვერ გადმოვა:
 * Python-ში `\b` Unicode-ია და `სლრ`-ს სიტყვად თვლის, JS-ში `\b` მხოლოდ
 * ASCII-ს ცნობს — ქართულ ტექსტში საზღვარი **შებრუნებულად** მუშაობს და
 * `სლრ` საერთოდ არ დაიჭირებოდა. ამიტომ საზღვარი ცალსახად წერია
 * `[\p{L}\p{N}_]`-ით (Unicode ასო/ციფრი), `u` დროშით.
 */
function N(s) {
  s = String(s == null ? '' : s).toLowerCase();
  s = s.replace(/\u0451/g, '').replace(/\u00a0/g, ' ');
  s = s.replace(
    /(?<![\p{L}\p{N}_])(?:slr(?![\p{L}\p{N}_])|სლრ(?![\p{L}\p{N}_])|ესელერ)/gu,
    ' slr ');
  s = s.replace(/[«»„“”"'`]/g, ' ');
  s = s.replace(/\s+/g, ' ');
  return s;
}

/** კოდები ჯერ არ მინიჭებულა? (Python-ის `not out`-ის ეკვივალენტი) */
function empty(o) {
  for (var k in o) if (o[k]) return false;
  return true;
}

