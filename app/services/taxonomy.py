def N(s):
    """ნორმალიზება: lowercase, ლათინური SLR ვარიანტები, ზედმეტი space."""
    s = str(s).lower()
    s = s.replace('ё','').replace(' ',' ')
    s = re.sub(r'\bslr\b|\bსლრ\b|\bესელერ', ' slr ', s)
    s = re.sub(r'[«»„“”"\'`]', ' ', s)
    s = re.sub(r'\s+', ' ', s)
    return s

def has(t, *subs):
    return any(x in t for x in subs)

